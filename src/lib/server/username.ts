/**
 * Returns true if a candidate name is not in the forbidden usernames list and is not a currently registered username.
 */
export async function isAvailableUsername(candidate: string) {
  const candidateLower = candidate.toLowerCase()
  if (FORBIDDEN_USERNAMES.has(candidateLower)) return false
  // potential avatar-display conflicts (e.g. opengraph-image)
  if (/^[a-z]+-image$/.test(candidateLower)) return false
  // potential future route conflict with <userName>.example.com-style subdomains
  if (/^[a-z0-9]{2}--/.test(candidateLower)) return false // punycode
  if (/^auto\d*$/.test(candidateLower)) return false
  if (/^ns\d*$/.test(candidateLower)) return false
  if (/^shard\d*$/.test(candidateLower)) return false
  if (/^worker\d*$/.test(candidateLower)) return false
  if (/^www\d*$/.test(candidateLower)) return false
  return null === (await getDb().user.findUnique({ where: { name: candidate } }))
}

export async function checkUsername(candidate: string): Promise<ActionResponse<null>> {
  if (candidate.length > 63) return { error: 'Usernames must have at most 63 characters' }
  if (candidate.startsWith('-') || candidate.endsWith('-'))
    return { error: 'Usernames cannot begin or end with a hyphen' }
  if (!candidate.match(USERNAME_RE)) return { error: 'Usernames must contain only alphanumeric characters and hyphens' }
  if (!(await isAvailableUsername(candidate))) return { error: 'Username is not available' }
  return { ok: null }
}
